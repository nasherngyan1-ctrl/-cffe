import type { Language } from '../types/pos';

export function isRTL(lang: Language): boolean {
  return lang === 'ckb' || lang === 'ar';
}

export function formatIQD(value: number | string | null | undefined, currency = 'IQD'): string {
  const num = Number(value || 0);
  const formatted = Math.round(num).toLocaleString('en-US');
  return `${formatted} ${currency}`;
}

export function parseSqliteDate(iso?: string | null): Date | null {
  if (!iso) return null;
  const normalized = iso.includes('T') ? iso : `${iso.replace(' ', 'T')}Z`;
  const parsed = new Date(normalized);
  return Number.isNaN(parsed.getTime()) ? null : parsed;
}

export function formatLocalDateTime(iso?: string | null): string {
  const parsed = parseSqliteDate(iso);
  if (!parsed) return iso || '';
  return parsed.toLocaleString();
}

export function formatLocalTime(iso?: string | null): string {
  const parsed = parseSqliteDate(iso);
  if (!parsed) return iso || '';
  return parsed.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

export function formatLocalDate(iso?: string | null): string {
  const parsed = parseSqliteDate(iso);
  if (!parsed) return iso || '';
  return parsed.toLocaleDateString();
}

export function getLocalizedName(
  item: { name_ckb?: string; name_ar?: string; name_en?: string } | null | undefined,
  lang: Language
): string {
  if (!item) return '';
  if (lang === 'ckb') return item.name_ckb || item.name_en || '';
  if (lang === 'ar') return item.name_ar || item.name_en || '';
  return item.name_en || item.name_ckb || '';
}

export function getLocalizedDesc(
  item: { description_ckb?: string; description_ar?: string; description_en?: string } | null | undefined,
  lang: Language
): string {
  if (!item) return '';
  if (lang === 'ckb') return item.description_ckb || item.description_en || '';
  if (lang === 'ar') return item.description_ar || item.description_en || '';
  return item.description_en || '';
}

